#!/usr/bin/env python3
"""Build the five compatibility FNTs exclusively from the supplied font files.

No original FNT glyphs are read. Names/heights are the client's UI interface.
Pillow and fontTools are needed only to regenerate this checked-in output.
"""
from pathlib import Path
import base64
import hashlib
import json
import math
import struct

from PIL import Image, ImageDraw, ImageFont
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'src/mod/fonts'
sources = ['item-font-text.ttf', 'item-font-title.ttf', 'item-font-numbers.ttf']
faces = {name: ImageFont.truetype(str(FONTS / name), 96) for name in sources}
cmaps = {name: TTFont(FONTS / name).getBestCmap() for name in sources}
result = {}
for index, height in enumerate([11, 14, 5, 7, 6]):
    primary = 'item-font-title.ttf' if index in (0, 4) else 'item-font-text.ttf'
    order = [primary] + [name for name in sources if name != primary]
    top, bottom = faces[primary].getbbox('AgЙЁjQ', anchor='ls')[1::2]
    ratio = height / max(1, bottom - top)
    space = max(1, round(faces[primary].getlength(' ') * ratio))
    header = bytearray(struct.pack('<HH', space + 1, height))
    pixels = bytearray()
    for code in range(33, 273):
        name = next((n for n in order if code in cmaps[n]), primary)
        char = chr(code) if code in cmaps[name] else '?'
        font = faces[name]
        box = font.getbbox(char, anchor='ls')
        w, h = max(1, box[2] - box[0]), max(1, box[3] - box[1])
        high = Image.new('L', (w, h))
        ImageDraw.Draw(high).text((-box[0], -box[1]), char, font=font, fill=255, anchor='ls')
        gw, gh = min(16, max(1, math.ceil(w * ratio))), min(height, max(1, math.ceil(h * ratio)))
        glyph = high.resize((gw, gh), Image.Resampling.LANCZOS)
        width = min(16, max(gw, math.ceil(font.getlength(char) * ratio)))
        cell = Image.new('L', (16, 16))
        cell.paste(glyph, (0, min(height - gh, max(0, round((box[1] - top) * ratio)))))
        header.extend(struct.pack('<HH', 964 + len(pixels), width))
        for y in range(16):
            bits = sum(1 << (15 - x) for x in range(16) if cell.getpixel((x, y)) >= 80)
            pixels.extend(struct.pack('<H', bits))
    raw = bytes(header + pixels)
    result[str(height)] = {'name': f'FONT000{index}', 'base64': base64.b64encode(raw).decode()}
output = {'sources': {name: hashlib.sha256((FONTS / name).read_bytes()).hexdigest() for name in sources}, 'fonts': result}
js = "// Generated by tools/build-font-defaults.py from community fonts, not game glyphs.\n"
js += "(function(g){const data=" + json.dumps(output, separators=(',', ':')) + ";if(typeof module==='object'&&module.exports)module.exports=data;else g.__dfoFontData=data})(globalThis);\n"
(ROOT / 'src/mod/page/dfo_font_data.js').write_text(js)
print('Generated', len(result), 'compatibility faces; no original font files used.')
