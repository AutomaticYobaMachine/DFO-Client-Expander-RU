#!/usr/bin/env node
// The inventory's page tables (docs/inventory.md), read off the original's own sources - never typed by hand:
//   node tools/build-pack-data.mjs "$DFO_UPSTREAM_DIR"            writes src/mod/page/dfo_pack_data.js
//   node tools/build-pack-data.mjs "$DFO_UPSTREAM_DIR" --check    only compares (test/pack.test.cjs runs this)
// ingredients - every template a recipe of the game spends: the crafts' RECIPES (smithing, carpentry, outfitting,
//               jewelcrafting, masonry, cooking), the stations' WORK_RECIPES (smelt, saw, burn, cure, spin, weave, cut,
//               transmute), the Heartwood a recipe may take and the alchemy's POTIONS. A tool is never an ingredient: no
//               recipe spends one.
// sale        - the bases the description tables call "a thing to sell" (src/mod/item-text/hints.json, SALE_HINTS):
//               the default rule of the Junk page.
// notes       - the parchment: notes and quest letters read on the Books page (useItem.js isParchment).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const OUT = path.join(root, 'src/mod/page/dfo_pack_data.js');
// The description tables' hints whose words send the piece to a counter (en/properties/hints.csv).
export const SALE_HINTS = Object.freeze(['hint.trinket', 'hint.religious', 'hint.relic', 'hint.reagent.unused', 'hint.herb.plain',
  'hint.metal.brass', 'hint.quest-prop', 'hint.drug']);

export async function packData(upstream) {
  const src = (rel) => import(pathToFileURL(path.join(upstream, rel)).href);
  const [recipes, work, alchemy, items, use, spell] = await Promise.all([
    src('src/net/recipeLaw.js'), src('src/net/professionLaw.js'), src('src/net/alchemyLaw.js'),
    src('src/systems/professions/profItems.js'), src('src/systems/useItem.js'), src('src/systems/spell/spellMaker.js'),
  ]);
  const keys = new Set();
  for (const r of recipes.RECIPES) for (const i of r.inputs ?? []) keys.add(i.key);
  for (const r of work.WORK_RECIPES) for (const i of r.inputs ?? []) keys.add(i.key);
  keys.add(work.HEARTWOOD.key);   // recipeInputs({ heartwood }): a plank's stand-in
  const ingredients = new Set();
  for (const key of keys) {
    // a food mints two ways (Climates & Calories on or off): both are the same ingredient
    for (const cc of key.startsWith('food:') ? [true, false] : [undefined]) {
      let it = null;
      try { it = items.mintMaterialItem(key, cc); } catch { it = null; }
      if (it && Number.isInteger(it.templateIndex)) ingredients.add(it.templateIndex);
    }
  }
  for (const p of alchemy.POTIONS) for (const t of p.ingredients) ingredients.add(t);
  const hints = JSON.parse(fs.readFileSync(path.join(root, 'src/mod/item-text/hints.json'), 'utf8')).templates;
  const parchment = use.TEMPLATES.Parchment;
  const sale = Object.entries(hints).filter(([t, h]) => SALE_HINTS.includes(h) && Number(t) !== parchment).map(([t]) => Number(t));
  const clash = sale.filter((t) => ingredients.has(t));
  if (clash.length) throw new Error(`a recipe spends a base the hints call a thing to sell: ${clash.join(', ')}`);
  let head = '';
  try { head = fs.readFileSync(path.join(upstream, '.git/HEAD'), 'utf8').trim(); } catch { /* not a checkout */ }
  const sort = (xs) => [...xs].sort((a, b) => a - b);
  return {
    ingredients: sort(ingredients), sale: sort(sale), notes: [parchment], spellbook: spell.SPELLBOOK_TEMPLATE_INDEX,
    _source: head.startsWith('ref:') ? head.slice(5) : head,
  };
}

export function render(data) {
  const body = JSON.stringify({ ingredients: data.ingredients, sale: data.sale, notes: data.notes, spellbook: data.spellbook });
  return `// Generated by tools/build-pack-data.mjs from the original's recipes and the description hints - do not edit.\n`
    + `// The inventory's pages (docs/inventory.md): what a recipe spends, what is a thing to sell, what is read as a note.\n`
    + `(function (root) {\n  'use strict';\n  const data = Object.freeze(${body});\n`
    + `  if (typeof module === 'object' && module.exports) module.exports = data;\n  else root.__dfoPackData = data;\n})(globalThis);\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const upstream = path.resolve(process.argv[2] || process.env.DFO_UPSTREAM_DIR || '');
  if (!fs.existsSync(path.join(upstream, 'src/net/recipeLaw.js'))) { console.error('usage: build-pack-data.mjs <daggerfall-js-source>'); process.exit(2); }
  const text = render(await packData(upstream));
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (now !== text) { console.error('src/mod/page/dfo_pack_data.js differs from the original\'s recipes: run tools/build-pack-data.mjs'); process.exit(1); }
    console.log('pack data matches the original');
  } else { fs.writeFileSync(OUT, text); console.log(`wrote ${path.relative(root, OUT)}`); }
}
