"use strict";
const assert = require("node:assert/strict");
const { standLocale, say } = require("./ui-text-stand.cjs");
// The windows' words: the translation's with the Russian pack, the game's own with the English one (no translation).
const ru = standLocale() === "ru";
const L = (russian, english) => (ru ? russian : english);
const selectors =
  ".port-win,.trade-win,.broker-win,.notice-win,.sb-shell>.px-win,.pick-win";
async function settle(page) {
  await page.evaluate(
    () =>
      new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r))),
  );
}
async function geometry(page, kind) {
  const rows = await page.evaluate((selector) => {
    const visible = (n) =>
      n.getBoundingClientRect().width > 0 &&
      getComputedStyle(n).visibility !== "hidden";
    const rect = (n) => {
      const r = n.getBoundingClientRect();
      return { x: r.x, y: r.y, width: r.width, height: r.height };
    };
    return [...document.querySelectorAll(selector)]
      .filter(visible)
      .map((n) => ({
        classes: n.className,
        ...rect(n),
        overflow: n.scrollWidth - n.clientWidth,
        feet: [...n.querySelectorAll(".port-foot,.dlg-acts,.packfoot")]
          .filter(visible)
          .map(rect),
        clipped: [
          ...n.querySelectorAll(
            ".port-spinlabel,.broker-price,.pick-label,.port-fieldlabel",
          ),
        ]
          .filter(visible)
          .filter((x) => x.scrollWidth > x.clientWidth + 2)
          .map((x) => x.textContent),
      }));
  }, selectors);
  assert.ok(rows.length, kind + " did not render a window");
  const { width, height } = page.viewportSize();
  for (const r of rows) {
    assert.ok(
      r.x >= -1 &&
        r.y >= -1 &&
        r.x + r.width <= width + 1 &&
        r.y + r.height <= height + 1,
      kind + " outside viewport " + JSON.stringify(r),
    );
    assert.ok(
      r.overflow <= 4,
      kind + " horizontal window overflow " + JSON.stringify(r),
    );
    assert.deepEqual(r.clipped, [], kind + " clipped labels");
    for (const f of r.feet)
      assert.ok(
        f.y >= -1 && f.y + f.height <= height + 1,
        kind + " footer inaccessible",
      );
  }
  return rows;
}
async function interactions(page) {
  const checks = [];
  const show = async (k) => {
    await page.evaluate((k) => servicesAudit.show(k), k);
    await settle(page);
  };
  const pass = (s) => checks.push(s);
  await show("spellmaker-editor");
  const catalog = await page.evaluate(() => {
    for (const e of servicesAudit.native.effects) {
      const r = __dfoServiceDetails.spell(
        e,
        auditWindow.slots[0].settings,
        servicesAudit.entity.level,
      );
      if (!r || /undefined|NaN|Infinity|\{\w+\}/.test(JSON.stringify(r)))
        throw Error("Unsupported native effect " + e.key);
      if (
        r.formula.length !==
        [e.duration, e.chance, e.magnitude].filter(Boolean).length +
          (e.type === 2 ? 1 : 0)
      )
        throw Error("Wrong support flags " + e.key);
    }
    return servicesAudit.native.effects.length;
  });
  pass(
    "All " +
      catalog +
      " native spell effect records have descriptions and matching parameter groups",
  );
  // Ensure expensive descriptions are not regenerated by the original frame loop.
  const cached = await page.evaluate(async () => {
    const original = __dfoServiceDetails;
    let calls = 0;
    globalThis.__dfoServiceDetails = {
      ...original,
      spell(...a) {
        calls++;
        return original.spell(...a);
      },
    };
    auditWindow.entity.level++;
    for (let i = 0; i < 30; i++) await new Promise(requestAnimationFrame);
    globalThis.__dfoServiceDetails = original;
    auditWindow.entity.level--;
    return calls;
  });
  assert.equal(cached, 1, "Description work repeated without model changes");
  pass(
    "30 unchanged native frames compute one description after a level change",
  );
  await settle(page);
  const before = await page.evaluate(
    () => auditWindow.slots[0].settings.magnitudeBaseLow,
  );
  await page
    .locator(".port-spin")
    .filter({ hasText: L("База: мин.", "Base min") })
    .locator(".port-spinfield")
    .fill("12");
  await page
    .locator(".port-spin")
    .filter({ hasText: L("База: мин.", "Base min") })
    .locator(".port-spinfield")
    .press("Enter");
  await settle(page);
  assert.equal(
    await page.evaluate(() => auditWindow.slots[0].settings.magnitudeBaseLow),
    12,
  );
  assert.equal(
    await page.evaluate(() => auditWindow.slots[0].settings.magnitudeBaseHigh),
    12,
    "Paired native max must follow min",
  );
  assert.match(
    await page.locator(".dfo-service-description").innerText(),
    /28–44/,
  );
  await page.getByRole("button", { name: L("Готово", "Done"), exact: true }).click();
  await settle(page);
  assert.equal(await page.evaluate(() => !!auditWindow.editor), false);
  assert.equal(await page.locator(".port-host").count(), 1);
  assert.equal(
    await page.evaluate(() => auditWindow.slots[0].settings.magnitudeBaseLow),
    12,
  );
  assert.ok(before !== 12);
  pass(
    "Typing commits native min/max pairs, recalculates preview and closes only the effect editor",
  );
  await show("spellmaker-editor-absorb");
  const chance = page
    .locator(".port-group.port-spins")
    .filter({ hasText: L("Вероятность", "Chance") })
    .locator(".port-spinfield")
    .first();
  await chance.fill("999");
  await chance.press("Enter");
  await settle(page);
  assert.equal(
    await page.evaluate(() => auditWindow.slots[0].settings.chanceBase),
    50,
  );
  assert.match(
    await page.locator(".dfo-service-description").innerText(),
    /50%/,
  );
  pass(
    "Absorption input preserves the original 50 cap and the preview matches it",
  );

  await show("spellmaker-picker");
  const noMutation = await page.evaluate(() =>
    JSON.stringify(auditWindow.slots),
  );
  const first = await page.locator(".dfo-service-help").innerText();
  assert.match(first,L(/Обычный · Истинный/i,/Normal · True/),'True is an effect variant, not the boolean Yes');
  await page.locator(".pick-row").nth(1).hover();
  assert.notEqual(await page.locator(".dfo-service-help").innerText(), first);
  assert.equal(
    await page.evaluate(() => JSON.stringify(auditWindow.slots)),
    noMutation,
  );
  await page.mouse.move(5, 5);
  await page.keyboard.press("ArrowDown");
  await settle(page);
  assert.equal(
    await page.locator('.pick-row[aria-selected="true"]').count(),
    1,
  );
  await page.keyboard.press("Escape");
  await settle(page);
  await page.waitForFunction(
    () => !document.querySelector(".dfo-service-picker"),
    { timeout: 2000 },
  );
  assert.equal(await page.locator(".dfo-service-picker").count(), 0);
  assert.equal(await page.locator(".port-host").count(), 1);
  pass(
    "Picker mouse/keyboard previews do not add effects; Escape returns to one parent",
  );

  await show("spellmaker-variant");
  // Health is already present in this spell; the native duplicate guard must
  // remain effective. Select a different actual subtype for the add flow.
  await page.locator(".pick-row").filter({ hasText: L("Мана", /Spell Points|Magicka|Mana/) }).click();
  await settle(page);
  assert.ok(
    await page.evaluate(() => !!auditWindow.editor),
    "Native row replay must open the selected editor",
  );
  assert.equal(
    await page.evaluate(() => auditWindow.editor.deps.effect.key),
    "4,2",
  );
  assert.equal(await page.locator(".pick-shell").count(), 0);
  pass(
    "Actual picker click replays the original choice into the correct effect editor",
  );
  await show('spellmaker-picker');
  await page.evaluate(()=>auditWindow._pickGroup('Invisibility'));await settle(page);
  assert.equal(await page.evaluate(()=>auditWindow.picker.items.includes('True')),true);
  await page.locator('.pick-row').filter({hasText:L('Истинный','True')}).click();await settle(page);
  assert.equal(await page.evaluate(()=>auditWindow.editor.deps.effect.key),'13,1');
  pass('Normal/True labels keep the canonical effect keys and choose true invisibility');

  await show("enchant-parameter");
  const itemBefore = await page.evaluate(() =>
    JSON.stringify(servicesAudit.bag),
  );
  await page
    .locator(".pick-row")
    .filter({ hasText: L("Критический удар", "Critical Strike") })
    .click();
  await settle(page);
  assert.equal(
    await page.evaluate(() =>
      auditWindow._lists().powers.some((p) => p.type === "EnhancesSkill"),
    ),
    true,
  );
  assert.equal(
    await page.evaluate(() => JSON.stringify(servicesAudit.bag)),
    itemBefore,
    "Choosing a proposed enchant must not enchant the actual item",
  );
  assert.equal(await page.locator(".pick-shell").count(), 0);
  pass(
    "Enchantment choice uses the native param and budget, without mutating a bag item",
  );

  await show("enchant-spell");
  // The spell's own figures come from SPELLS.STD (ARENA2); without it the panel says the data is not loaded yet.
  if (process.env.DFO_ARENA2_DIR)
    assert.match(await page.locator(".dfo-service-help").innerText(), /M =/);
  else
    assert.ok((await page.locator(".dfo-service-help").innerText()).includes(say("svc.pick.spellLoading")));
  const panelCount = await page.locator(".dfo-service-help").count();
  assert.equal(panelCount, 1);
  await page.getByRole("button", { name: L(/Отмена/, /Cancel/) }).click();
  await settle(page);
  assert.equal(await page.locator(".dfo-service-help").count(), 0);
  pass(
    "Embedded spell figures come from the native SPELLS.STD reader; Cancel removes its panel",
  );

  await show("bank-deposit");
  const field = page.locator(".port-field[data-entry]");
  assert.equal(await field.count(), 1);
  await page.getByRole("button", { name: L("Отмена", "Cancel"), exact: true }).click();
  await settle(page);
  assert.equal(await field.count(), 0);
  assert.equal(await page.locator(".port-host").count(), 1);
  assert.equal(
    await page.evaluate(() => auditWindow.labels().account),
    "125000",
  );
  pass(
    "Bank transaction cancellation restores the main controls and leaves the balance intact",
  );

  await show("board-orders");
  assert.match(await page.locator(".notice-win").innerText(), L(/25 серебра/, /25 silver/i));
  const search = page.locator('.notice-win input[type="search"]');
  if (await search.count()) {
    await search.fill("no-such-order-xyz");
    await search.evaluate((n) => n.blur());
    await page.waitForFunction(
      (re) =>
        new RegExp(re).test(
          document.querySelector(".notice-win")?.innerText || "",
        ),
      L("Нет подходящих", "No work matches"),
    );
    await search.fill("");
    await search.evaluate((n) => n.blur());
  }
  pass("Town-order rewards and filter controls render in the install's language");

  for (const k of ["trade-buy", "trade-sell"]) {
    await show(k);
    const tab = page.locator(".packtab").filter({ hasText: L("Ингредиенты", "Ingredients") });
    await tab.click();
    await settle(page);
    await page
      .locator(".packtab")
      .filter({ hasText: L("Оружие и доспехи", "Weapons & Armor") })
      .click();
    await settle(page);
    assert.equal(await page.locator(".trade-win").count(), 1);
    // The translation must name the metals, not the languages of the same words.
    if (ru)
      assert.doesNotMatch(
        await page.locator(".trade-win").innerText(),
        /Язык орков|Язык даэдра|silver/i,
      );
    await page.locator(".itemrow").first().click();
    await settle(page);
    assert.equal(
      await page.locator(".trade-win .trade-detail-info").count(),
      1,
    );
  }
  pass(
    "Trade category changes and item selection retain one window and the native detail strip",
  );
  await show("spells");
  await page
    .locator(".sb-row")
    .filter({ hasText: "Поглощение заклинаний" }) // the fixture's own spell name, in both languages
    .click();
  await settle(page);
  assert.match(await page.locator(".px-qdetail").innerText(), /Поглощение заклинаний/i);
  pass("Spell selection switches the native detail pane");
  await page.evaluate(() => servicesAudit.stop());
  await settle(page);
  assert.equal(await page.locator(selectors).count(), 0);
  pass("Closing the stand removes all windows and help panels");
  return checks;
}
module.exports = { geometry, interactions, settle };
